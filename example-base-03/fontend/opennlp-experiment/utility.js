/**
 * Uses **node-nlp** (NLP.js), not Apache OpenNLP. The old package name `opennlp-node`
 * does not exist on npm; `NlpManager` comes from `node-nlp`.
 */
const { NlpManager } = require("node-nlp");

const nlpManager = new NlpManager({ languages: ["en"], nlu: { threshold: 0.1 } });

nlpManager.addDocument("en", "What is the capital of India?", "capital.india");
nlpManager.addAnswer("en", "capital.india", "The capital of India is New Delhi.");

/** Train once; `train()` returns a Promise — must complete before `process`. */
const nlpTraining = Promise.resolve(nlpManager.train());

/**
 * Processes a question using the NLP manager and returns the answer.
 *
 * @param {string} questionText - The question to process.
 * @returns {Promise<string>} - The answer generated by the NLP manager.
 */
async function getAnswer(questionText) {
  await nlpTraining;

  const response = await nlpManager.process("en", questionText);

  if (response?.answer) {
    return response.answer;
  }
  return "Sorry, I don't know the answer to that question.";
}

module.exports = {
  getAnswer,
};
